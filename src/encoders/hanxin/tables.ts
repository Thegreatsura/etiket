/**
 * Han Xin Code (ISO/IEC 20830) symbol metrics and fixed patterns.
 *
 * The tables are transcribed from BWIPP's `hanxin` encoder, which carries the
 * standard's per-version figures verbatim. They are stored as compact strings
 * so the 84-row table stays readable in source; `HANXIN_METRICS` parses them
 * once at module load.
 */

/** One Reed-Solomon block group: how many blocks, and their data / EC sizes. */
export interface HanXinBlockGroup {
  blocks: number
  dataCodewords: number
  ecCodewords: number
}

/** Everything the encoder needs to know about one symbol version. */
export interface HanXinMetric {
  /** Version number, 1-84. */
  version: number
  /** Symbol side length in modules. */
  size: number
  /** Regular alignment-pattern spacing (`-1` when the version has none). */
  alignK: number
  /** Number of regular alignment patterns (`0` for versions 1-3). */
  alignN: number
  /** Modules available for codewords, i.e. everything but the function patterns. */
  modules: number
  /** Block layout per EC level, indexed `[level - 1]`. */
  ec: HanXinBlockGroup[][]
}

