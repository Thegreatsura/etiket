/** Symbol side length for a version: 23 modules at version 1, +2 per version. */
export function hanxinSize(version: number): number {
  return version * 2 + 21
}

function parseMetric(raw: string, index: number): HanXinMetric {
  const [head, ...levels] = raw.split(";")
  const [alignK, alignN, modules] = head!.split(" ").map(Number) as [number, number, number]
  return {
    version: index + 1,
    size: hanxinSize(index + 1),
    alignK,
    alignN,
    modules,
    ec: levels.map((level) =>
      level.split("/").map((group) => {
        const [blocks, dataCodewords, ecCodewords] = group.split(" ").map(Number) as [
          number,
          number,
          number,
        ]
        return { blocks, dataCodewords, ecCodewords }
      }),
    ),
  }
}

/** Symbol metrics for versions 1-84, indexed by `version - 1`. */
export const HANXIN_METRICS: readonly HanXinMetric[] = RAW_METRICS.map(parseMetric)

