/**
 * The four mask patterns. Each takes the 1-based module coordinates and the
 * module is inverted when the result is zero. Pattern 1 is the identity: it
 * never returns zero, so it leaves the symbol unmasked.
 */
export const HANXIN_MASKS: readonly ((x: number, y: number) => number)[] = [
  () => 1,
  (x, y) => (x + y) % 2,
  (x, y) => (((x + y) % 3) + (x % 3)) % 2,
  (x, y) => ((x % y) + (y % x) + (x % 3) + (y % 3)) % 2,
]

/**
 * The 34 function-information bit positions, as `[x, y]` pairs. Every bit is
 * written twice — once next to the top-left finder and once, rotated 180
 * degrees, next to the bottom-right one — so the information survives damage to
 * either corner.
 */
export function hanxinFunctionMap(size: number): [number, number][][] {
  const map: [number, number][][] = []
  for (let i = 0; i <= 8; i++)
    map.push([
      [i, 8],
      [size - 1 - i, size - 9],
    ])
  for (let k = 0; k <= 7; k++)
    map.push([
      [8, 7 - k],
      [size - 9, size - 8 + k],
    ])
  for (let k = 0; k <= 8; k++)
    map.push([
      [size - 9, k],
      [8, size - 1 - k],
    ])
  for (let k = 0; k <= 7; k++)
    map.push([
      [size - 8 + k, 8],
      [7 - k, size - 9],
    ])
  return map
}
